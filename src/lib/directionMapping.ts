const COMBOS: [MappingFeel, MappingTelling][] = [["approachable", "story"], ["approachable", "data"], ["formal", "story"], ["formal", "data"]];

export const DIRECTION_MAPPINGS: DirectionMapping[] = GOAL_ORDER.flatMap((goal, g) =>
  COMBOS.map(([feel, telling], k) => {
    const i = g * 4 + k;
    return { id: String(i + 1).padStart(2, "0"), goal, feel, telling, headline: TEXT[i][0], sentence: TEXT[i][1] };
  }),
);

/** The mapping for a draft: goal #1 + the answers to quiz q1 (feel) and q3 (telling).
 *  Null until all three are known, or when goal #1 is one the sheet doesn't cover. */
export function directionMappingFor(draft: { businessGoals?: string[]; quizPicks?: { questionId: string; letter: "A" | "B" }[] } | null | undefined): DirectionMapping | null {
  const goal = draft?.businessGoals?.[0];
  const pick = (q: string) => draft?.quizPicks?.find((p) => p.questionId === q)?.letter;
  const q1 = pick("q1"), q3 = pick("q3");
  if (!goal || !q1 || !q3) return null;
  const feel: MappingFeel = q1 === "A" ? "approachable" : "formal";
  const telling: MappingTelling = q3 === "A" ? "story" : "data";
  return DIRECTION_MAPPINGS.find((m) => m.goal === goal && m.feel === feel && m.telling === telling) ?? null;
}
